// `Frontend` construct: private S3 bucket, CloudFront distribution with OAC, the
// deployment of `frontend/dist` and the three response-header policies.

import { Duration, RemovalPolicy } from 'aws-cdk-lib';
import {
  AllowedMethods,
  CachePolicy,
  Distribution,
  HeadersReferrerPolicy,
  OriginRequestPolicy,
  PriceClass,
  ResponseHeadersPolicy,
  ViewerProtocolPolicy,
} from 'aws-cdk-lib/aws-cloudfront';
import { HttpOrigin, S3BucketOrigin } from 'aws-cdk-lib/aws-cloudfront-origins';
import { BlockPublicAccess, Bucket, BucketEncryption } from 'aws-cdk-lib/aws-s3';
import { BucketDeployment, CacheControl, Source } from 'aws-cdk-lib/aws-s3-deployment';
import { Construct } from 'constructs';

export interface FrontendProps {
  /** Host of the HTTP API (no scheme): the origin of `/api/*`. */
  readonly apiHost: string;
  /** Host of the WebSocket API (no scheme): allowed by the Panel's CSP. */
  readonly wsHost: string;
  /** Folder with the built frontend (`index.html`, `panel.html`, `assets/`). */
  readonly assetPath: string;
}

/** Content-Security-Policy of the public page: everything from the same origin. */
export function publicCsp(): string {
  return [
    "default-src 'self'",
    "script-src 'self'",
    "style-src 'self'",
    "img-src 'self' data:",
    "connect-src 'self'",
    "frame-ancestors 'none'",
    "base-uri 'none'",
    "form-action 'self'",
  ].join('; ');
}

/** Content-Security-Policy of the Panel: the same, plus its WebSocket. */
export function panelCsp(wsHost: string): string {
  return publicCsp().replace("connect-src 'self'", `connect-src 'self' wss://${wsHost}`);
}

export class Frontend extends Construct {
  readonly bucket: Bucket;
  readonly distribution: Distribution;

  constructor(scope: Construct, id: string, props: FrontendProps) {
    super(scope, id);

    // Private bucket: only CloudFront can read it, through an OAC.
    this.bucket = new Bucket(this, 'SiteBucket', {
      blockPublicAccess: BlockPublicAccess.BLOCK_ALL,
      encryption: BucketEncryption.S3_MANAGED,
      enforceSSL: true,
      removalPolicy: RemovalPolicy.DESTROY,
      autoDeleteObjects: true,
    });

    const securityHeaders = (csp: string) => ({
      contentSecurityPolicy: { contentSecurityPolicy: csp, override: true },
      strictTransportSecurity: {
        accessControlMaxAge: Duration.days(365),
        includeSubdomains: true,
        override: true,
      },
      contentTypeOptions: { override: true },
      referrerPolicy: {
        referrerPolicy: HeadersReferrerPolicy.STRICT_ORIGIN_WHEN_CROSS_ORIGIN,
        override: true,
      },
    });

    const publicHeaders = new ResponseHeadersPolicy(this, 'PublicHeaders', {
      securityHeadersBehavior: securityHeaders(publicCsp()),
    });
    const panelHeaders = new ResponseHeadersPolicy(this, 'PanelHeaders', {
      securityHeadersBehavior: securityHeaders(panelCsp(props.wsHost)),
      customHeadersBehavior: {
        customHeaders: [{ header: 'X-Robots-Tag', value: 'noindex', override: true }],
      },
    });
    // The 429 of the throttling and a 404 for an unknown route are generated by
    // API Gateway, not by the Lambda, so only this policy can make them `no-store`.
    const apiHeaders = new ResponseHeadersPolicy(this, 'ApiHeaders', {
      customHeadersBehavior: {
        customHeaders: [{ header: 'Cache-Control', value: 'no-store', override: true }],
      },
    });

    const siteOrigin = S3BucketOrigin.withOriginAccessControl(this.bucket);

    // No access logs: they would store the visitors' IP addresses. PRICE_CLASS_100
    // keeps the demo cheap (North America and Europe edge locations only).
    this.distribution = new Distribution(this, 'Distribution', {
      defaultRootObject: 'index.html',
      enableLogging: false,
      priceClass: PriceClass.PRICE_CLASS_100,
      defaultBehavior: {
        origin: siteOrigin,
        viewerProtocolPolicy: ViewerProtocolPolicy.REDIRECT_TO_HTTPS,
        responseHeadersPolicy: publicHeaders,
      },
      additionalBehaviors: {
        '/api/*': {
          origin: new HttpOrigin(props.apiHost),
          viewerProtocolPolicy: ViewerProtocolPolicy.REDIRECT_TO_HTTPS,
          allowedMethods: AllowedMethods.ALLOW_ALL,
          cachePolicy: CachePolicy.CACHING_DISABLED,
          originRequestPolicy: OriginRequestPolicy.ALL_VIEWER_EXCEPT_HOST_HEADER,
          responseHeadersPolicy: apiHeaders,
        },
        '/panel.html': {
          origin: siteOrigin,
          viewerProtocolPolicy: ViewerProtocolPolicy.REDIRECT_TO_HTTPS,
          responseHeadersPolicy: panelHeaders,
        },
      },
    });

    // Two deployments because the cache headers differ: hashed files in
    // `assets/` never change (`immutable`), HTML files must be revalidated
    // (`no-cache`). `prune` is off because each deployment only sees part of the
    // folder and would delete the other's files; hashed names make leftovers
    // harmless. The HTML goes last and invalidates CloudFront.
    const assets = new BucketDeployment(this, 'DeployAssets', {
      sources: [Source.asset(props.assetPath, { exclude: ['*.html'] })],
      destinationBucket: this.bucket,
      cacheControl: [CacheControl.fromString('public, max-age=31536000, immutable')],
      prune: false,
    });
    const pages = new BucketDeployment(this, 'DeployPages', {
      sources: [Source.asset(props.assetPath, { exclude: ['*', '!*.html'] })],
      destinationBucket: this.bucket,
      cacheControl: [CacheControl.noCache()],
      distribution: this.distribution,
      distributionPaths: ['/*'],
      prune: false,
    });
    pages.node.addDependency(assets);
  }
}
